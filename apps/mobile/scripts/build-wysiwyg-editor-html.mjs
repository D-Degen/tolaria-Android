import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const mobileRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(mobileRoot, "..", "..");
const entryPoint = path.join(
	mobileRoot,
	"src/components/workspace/MobileWysiwygTentapWebEditor.tsx",
);
const mobileReactResolver = {
	name: "mobile-react-resolver",
	setup(build) {
		build.onResolve({ filter: /^react($|\/)|^react-dom($|\/)/ }, (args) => ({
			path: require.resolve(args.path, { paths: [mobileRoot] }),
		}));
	},
};

export function buildEditorBundle() {
	return build({
		absWorkingDir: repoRoot,
		alias: {
			"@10play/tentap-editor/web": path.join(
				path.dirname(require.resolve("@10play/tentap-editor/package.json")),
				"src/webEditorUtils/index.ts",
			),
		},
		bundle: true,
		define: { "process.env.NODE_ENV": '"production"' },
		entryPoints: [entryPoint],
		external: ["expo-constants"],
		format: "iife",
		jsx: "automatic",
		metafile: true,
		minify: true,
		outfile: "editor.js",
		platform: "browser",
		plugins: [mobileReactResolver],
		write: false,
	});
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const result = await buildEditorBundle();
	const bundle = result.outputFiles.find((file) =>
		file.path.endsWith(".js"),
	)?.text;
	if (!bundle) throw new Error("Missing mobile editor bundle");
	process.chdir(repoRoot);
	await fs.writeFile(
		"apps/mobile/src/components/workspace/MobileWysiwygTentapEditorHtml.ts",
		generatedEditorHtmlModule(editorHtml(bundle)),
	);
}

function editorHtml(bundle) {
	return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
    <title>Tolaria Mobile WYSIWYG Editor</title>
    <style>
      body {
        margin: 0;
        padding: 0;
      }

      #root > div:nth-of-type(1) {
        position: absolute;
        height: 100%;
        overflow: auto;
        width: 100%;
        top: 0;
        bottom: 0;
        scroll-padding-bottom: 56px;
      }

      #root > div.dynamic-height {
        height: unset;
      }

      #root div .ProseMirror {
        min-height: 100%;
        overflow: visible;
      }

      #root div.dynamic-height .ProseMirror {
        height: unset;
      }

      .ProseMirror:focus {
        outline: none;
      }

      .highlight-background {
        background-color: #e6e6ff;
      }
    </style>
  </head>
  <body>
    <div id="root"></div>
    <script>${bundle}</script>
  </body>
</html>`;
}

function generatedEditorHtmlModule(html) {
	return `// Generated by apps/mobile/scripts/build-wysiwyg-editor-html.mjs.
export const mobileWysiwygTentapEditorHtml = ${JSON.stringify(html)}
`;
}
